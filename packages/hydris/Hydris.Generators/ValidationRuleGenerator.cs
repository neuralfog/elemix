using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hydris.Generators;

[Generator]
public sealed class ValidationRuleGenerator : IIncrementalGenerator {
    private static readonly SymbolDisplayFormat FullyQualified = SymbolDisplayFormat.FullyQualifiedFormat;

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var rules = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Hydris.Validation.ValidationRuleAttribute",
            static (node, _) => node is ClassDeclarationSyntax,
            static (syntax, _) => Registration(syntax));

        context.RegisterSourceOutput(rules.Collect(), static (production, data) => Emit(production, data));
    }

    private static string? Registration(GeneratorAttributeSyntaxContext syntax) {
        if (syntax.TargetSymbol is not INamedTypeSymbol type)
            return null;

        string? name = null;
        if (syntax.Attributes.Length > 0 && syntax.Attributes[0].ConstructorArguments.Length > 0)
            name = syntax.Attributes[0].ConstructorArguments[0].Value as string;
        name ??= Snake(type.Name);

        return $"global::Hydris.Validation.Rules.Register({Literal(name)}, new {type.ToDisplayString(FullyQualified)}());";
    }

    private static string Literal(string value) =>
        Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private static string Snake(string name) {
        var builder = new StringBuilder();
        for (var i = 0; i < name.Length; i++) {
            var c = name[i];
            if (char.IsUpper(c)) {
                if (i > 0)
                    builder.Append('_');
                builder.Append(char.ToLowerInvariant(c));
            } else {
                builder.Append(c);
            }
        }

        return builder.ToString();
    }

    private static void Emit(SourceProductionContext production, ImmutableArray<string?> registrations) {
        var lines = new List<string>();
        foreach (var registration in registrations) {
            if (registration is not null)
                lines.Add(registration);
        }

        if (lines.Count == 0)
            return;

        lines.Sort(StringComparer.Ordinal);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Hydris.Validation.Generated");
        sb.AppendLine("{");
        sb.AppendLine("    internal static class GeneratedValidationRules");
        sb.AppendLine("    {");
        sb.AppendLine("        [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("        internal static void Initialize()");
        sb.AppendLine("        {");
        foreach (var line in lines)
            sb.Append("            ").AppendLine(line);
        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        production.AddSource("GeneratedValidationRules.g.cs", sb.ToString());
    }
}
