using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hydris.Generators;

[Generator]
public sealed class ContractGenerator : IIncrementalGenerator {
    private static readonly SymbolDisplayFormat FullyQualified = SymbolDisplayFormat.FullyQualifiedFormat;

    private static readonly DiagnosticDescriptor Unsupported = new(
        "HYD010",
        "Unsupported [Contract] property type",
        "Property '{0}' of type '{1}' is not supported by [Contract]; use string, bool or a numeric type (nested types, arrays and enums are not supported yet)",
        "Hydris",
        DiagnosticSeverity.Error,
        true);

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Hydris.Contracts.ContractAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol);

        var usages = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Hydris.Routing.ActionAttribute",
            static (node, _) => node is MethodDeclarationSyntax,
            static (syntax, _) => Usage(syntax));

        var combined = types.Collect().Combine(usages.Collect());
        context.RegisterSourceOutput(combined, static (production, data) => {
            var requests = new HashSet<string>();
            var responses = new HashSet<string>();
            foreach (var usage in data.Right) {
                if (usage.Request is not null)
                    requests.Add(usage.Request);
                if (usage.Response is not null)
                    responses.Add(usage.Response);
            }

            foreach (var type in data.Left) {
                var full = type.ToDisplayString(FullyQualified);
                Emit(production, type, requests.Contains(full), responses.Contains(full));
            }
        });
    }

    private static (string? Request, string? Response) Usage(GeneratorAttributeSyntaxContext syntax) {
        if (syntax.TargetSymbol is not IMethodSymbol method)
            return (null, null);

        var request = method.Parameters.Length == 1
            ? method.Parameters[0].Type.ToDisplayString(FullyQualified)
            : null;
        return (request, Unwrap(method.ReturnType).ToDisplayString(FullyQualified));
    }

    private static ITypeSymbol Unwrap(ITypeSymbol type) {
        if (type is INamedTypeSymbol named
            && named.TypeArguments.Length == 1
            && (named.Name == "Task" || named.Name == "ValueTask")
            && named.ContainingNamespace?.ToDisplayString() == "System.Threading.Tasks")
            return named.TypeArguments[0];

        return type;
    }

    private static void Emit(SourceProductionContext production, INamedTypeSymbol type, bool isRequest, bool isResponse) {
        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
        var keyword = type.IsRecord ? "record" : "class";
        var members = Members(type);
        var needsWrite = isResponse || !isRequest;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (ns is not null) {
            sb.Append("namespace ").AppendLine(ns);
            sb.AppendLine("{");
        }
        sb.Append("    partial ").Append(keyword).Append(' ').Append(type.Name);
        sb.AppendLine(needsWrite ? " : global::Hydris.Http.IViewData" : string.Empty);
        sb.AppendLine("    {");
        if (needsWrite)
            EmitWrite(production, sb, type, members);
        if (isRequest) {
            if (needsWrite)
                sb.AppendLine();
            EmitParse(production, sb, type, members);
            sb.AppendLine();
            EmitValidate(sb, type, members);
        }
        sb.AppendLine("    }");
        if (ns is not null)
            sb.AppendLine("}");

        var hint = type.ToDisplayString(FullyQualified).Replace("global::", string.Empty).Replace('.', '_');
        production.AddSource($"{hint}.Contract.g.cs", sb.ToString());
    }

    private static void EmitWrite(
        SourceProductionContext production, StringBuilder sb, INamedTypeSymbol type, IReadOnlyList<Member> members) {
        sb.AppendLine("        void global::Hydris.Http.IViewData.Write(global::System.Text.Json.Utf8JsonWriter writer)");
        sb.AppendLine("        {");
        sb.AppendLine("            writer.WriteStartObject();");
        foreach (var member in members) {
            var kind = Classify(member.Type);
            if (kind == Kind.Unsupported) {
                production.ReportDiagnostic(Diagnostic.Create(Unsupported, member.Location, member.Name, member.Type.ToDisplayString()));
                continue;
            }
            var write = kind == Kind.String ? "WriteString" : kind == Kind.Boolean ? "WriteBoolean" : "WriteNumber";
            sb.Append("            writer.").Append(write).Append("(\"").Append(member.Wire).Append("\", this.").Append(member.Name).AppendLine(");");
        }
        sb.AppendLine("            writer.WriteEndObject();");
        sb.AppendLine("        }");
    }

    private static void EmitParse(
        SourceProductionContext production, StringBuilder sb, INamedTypeSymbol type, IReadOnlyList<Member> members) {
        var typeName = type.Name;
        sb.Append("        public static ").Append(typeName).Append("? Parse(global::System.ReadOnlySpan<byte> utf8, global::Hydris.Contracts.ContractValidation errors)");
        sb.AppendLine();
        sb.AppendLine("        {");
        sb.AppendLine("            var reader = new global::System.Text.Json.Utf8JsonReader(utf8);");
        sb.AppendLine("            if (!reader.Read() || reader.TokenType != global::System.Text.Json.JsonTokenType.StartObject)");
        sb.AppendLine("            {");
        sb.AppendLine("                errors.Add(\"\", \"invalid\", \"Expected a JSON object.\");");
        sb.AppendLine("                return null;");
        sb.AppendLine("            }");
        foreach (var member in members) {
            var kind = Classify(member.Type);
            if (kind == Kind.Unsupported)
                continue;
            sb.Append("            ").Append(member.Type.ToDisplayString(FullyQualified)).Append(' ').Append(member.Local).Append(" = ").Append(Default(kind)).AppendLine(";");
        }
        sb.AppendLine("            while (reader.Read() && reader.TokenType == global::System.Text.Json.JsonTokenType.PropertyName)");
        sb.AppendLine("            {");
        sb.AppendLine("                var name = reader.GetString();");
        sb.AppendLine("                reader.Read();");
        sb.AppendLine("                switch (name)");
        sb.AppendLine("                {");
        foreach (var member in members) {
            var kind = Classify(member.Type);
            if (kind == Kind.Unsupported)
                continue;
            sb.Append("                    case \"").Append(member.Wire).Append("\": ").Append(member.Local).Append(" = ").Append(ReadExpr(member.Type, kind)).AppendLine("; break;");
        }
        sb.AppendLine("                    default: reader.Skip(); break;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        var arguments = string.Join(", ", members.Where(m => Classify(m.Type) != Kind.Unsupported).Select(m => m.Local));
        sb.Append("            var value = new ").Append(typeName).Append('(').Append(arguments).AppendLine(");");
        sb.AppendLine("            Validate(value, errors);");
        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
    }

    private static void EmitValidate(StringBuilder sb, INamedTypeSymbol type, IReadOnlyList<Member> members) {
        sb.Append("        private static void Validate(").Append(type.Name).AppendLine(" value, global::Hydris.Contracts.ContractValidation errors)");
        sb.AppendLine("        {");
        foreach (var member in members) {
            var kind = Classify(member.Type);
            if (kind == Kind.Unsupported)
                continue;
            var access = "value." + member.Name;
            foreach (var rule in member.Rules) {
                switch (rule.Name) {
                    case "Required":
                        if (kind == Kind.String)
                            sb.Append("            if (string.IsNullOrEmpty(").Append(access).Append(")) errors.Add(\"").Append(member.Wire).Append("\", \"required\", \"").Append(member.Label).AppendLine(" is required.\");");
                        break;
                    case "Length":
                        if (kind == Kind.String) {
                            sb.Append("            if (").Append(access).Append(" is not null && (").Append(access).Append(".Length < ").Append(rule.Min).Append(" || ").Append(access).Append(".Length > ").Append(rule.Max).Append(")) errors.Add(\"").Append(member.Wire).Append("\", \"length\", \"").Append(member.Label).Append(" must be between ").Append(rule.Min).Append(" and ").Append(rule.Max).AppendLine(" characters.\");");
                        }
                        break;
                    case "Range":
                        if (kind == Kind.Number)
                            sb.Append("            if (").Append(access).Append(" < ").Append(rule.Min).Append(" || ").Append(access).Append(" > ").Append(rule.Max).Append(") errors.Add(\"").Append(member.Wire).Append("\", \"range\", \"").Append(member.Label).Append(" must be between ").Append(rule.Min).Append(" and ").Append(rule.Max).AppendLine(".\");");
                        break;
                    case "Email":
                        if (kind == Kind.String)
                            sb.Append("            if (!string.IsNullOrEmpty(").Append(access).Append(") && !").Append(access).Append(".Contains(\"@\")) errors.Add(\"").Append(member.Wire).Append("\", \"email\", \"").Append(member.Label).AppendLine(" must be a valid email address.\");");
                        break;
                }
            }
        }
        sb.AppendLine("        }");
    }

    private static IReadOnlyList<Member> Members(INamedTypeSymbol type) {
        var parameterAttributes = new Dictionary<string, ImmutableArray<AttributeData>>();
        foreach (var constructor in type.InstanceConstructors) {
            if (constructor.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(constructor.Parameters[0].Type, type))
                continue;
            foreach (var parameter in constructor.Parameters)
                parameterAttributes[parameter.Name] = parameter.GetAttributes();
        }

        var primary = type.InstanceConstructors
            .Where(c => !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, type)))
            .OrderByDescending(c => c.Parameters.Length)
            .FirstOrDefault();
        if (primary is null)
            return new List<Member>();

        var members = new List<Member>();
        foreach (var parameter in primary.Parameters) {
            var attributes = parameterAttributes.TryGetValue(parameter.Name, out var found) ? found : ImmutableArray<AttributeData>.Empty;
            members.Add(new Member(parameter.Name, parameter.Type, Camel(parameter.Name), Rules(attributes), parameter.Locations.FirstOrDefault()));
        }

        return members;
    }

    private static IReadOnlyList<Rule> Rules(ImmutableArray<AttributeData> attributes) {
        var rules = new List<Rule>();
        foreach (var attribute in attributes) {
            var name = attribute.AttributeClass?.ToDisplayString();
            switch (name) {
                case "Hydris.Contracts.RequiredAttribute":
                    rules.Add(new Rule("Required", null, null));
                    break;
                case "Hydris.Contracts.LengthAttribute":
                    rules.Add(new Rule("Length", Arg(attribute, 0), Arg(attribute, 1)));
                    break;
                case "Hydris.Contracts.RangeAttribute":
                    rules.Add(new Rule("Range", Arg(attribute, 0), Arg(attribute, 1)));
                    break;
                case "Hydris.Contracts.PatternAttribute":
                    rules.Add(new Rule("Pattern", null, null));
                    break;
                case "Hydris.Contracts.EmailAttribute":
                    rules.Add(new Rule("Email", null, null));
                    break;
            }
        }

        return rules;
    }

    private static string? Arg(AttributeData attribute, int index) =>
        attribute.ConstructorArguments.Length > index ? attribute.ConstructorArguments[index].Value?.ToString() : null;

    private static Kind Classify(ITypeSymbol type) {
        if (type.SpecialType == SpecialType.System_String)
            return Kind.String;
        if (type.SpecialType == SpecialType.System_Boolean)
            return Kind.Boolean;
        if (IsNumeric(type.SpecialType))
            return Kind.Number;

        return Kind.Unsupported;
    }

    private static bool IsNumeric(SpecialType type) => type
        is SpecialType.System_Byte
        or SpecialType.System_SByte
        or SpecialType.System_Int16
        or SpecialType.System_UInt16
        or SpecialType.System_Int32
        or SpecialType.System_UInt32
        or SpecialType.System_Int64
        or SpecialType.System_UInt64
        or SpecialType.System_Single
        or SpecialType.System_Double
        or SpecialType.System_Decimal;

    private static string Default(Kind kind) => kind switch {
        Kind.String => "string.Empty",
        Kind.Boolean => "false",
        _ => "0",
    };

    private static string ReadExpr(ITypeSymbol type, Kind kind) {
        if (kind == Kind.String)
            return "reader.GetString() ?? string.Empty";
        if (kind == Kind.Boolean)
            return "reader.GetBoolean()";
        return type.SpecialType switch {
            SpecialType.System_Int64 => "reader.GetInt64()",
            SpecialType.System_Double => "reader.GetDouble()",
            SpecialType.System_Single => "reader.GetSingle()",
            SpecialType.System_Decimal => "reader.GetDecimal()",
            SpecialType.System_Int16 => "reader.GetInt16()",
            SpecialType.System_Byte => "reader.GetByte()",
            SpecialType.System_SByte => "reader.GetSByte()",
            SpecialType.System_UInt16 => "reader.GetUInt16()",
            SpecialType.System_UInt32 => "reader.GetUInt32()",
            SpecialType.System_UInt64 => "reader.GetUInt64()",
            _ => "reader.GetInt32()",
        };
    }

    private static string Camel(string name) =>
        name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

    private enum Kind {
        Unsupported,
        String,
        Boolean,
        Number,
    }

    private sealed class Member {
        public Member(string name, ITypeSymbol type, string wire, IReadOnlyList<Rule> rules, Location? location) {
            Name = name;
            Type = type;
            Wire = wire;
            Rules = rules;
            Location = location;
            Label = wire;
            Local = "arg" + name;
        }

        public string Name { get; }
        public ITypeSymbol Type { get; }
        public string Wire { get; }
        public string Label { get; }
        public string Local { get; }
        public IReadOnlyList<Rule> Rules { get; }
        public Location? Location { get; }
    }

    private sealed class Rule {
        public Rule(string name, string? min, string? max) {
            Name = name;
            Min = min;
            Max = max;
        }

        public string Name { get; }
        public string? Min { get; }
        public string? Max { get; }
    }
}
