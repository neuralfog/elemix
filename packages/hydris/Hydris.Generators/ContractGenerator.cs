using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hydris.Generators;

[Generator]
public sealed class ContractGenerator : IIncrementalGenerator {
    private static readonly SymbolDisplayFormat FullyQualified = SymbolDisplayFormat.FullyQualifiedFormat;

    private static readonly DiagnosticDescriptor Unsupported = new(
        "HYD010",
        "Unsupported [Contract] property type",
        "Property '{0}' of type '{1}' is not supported by [Contract]; use string, bool or a numeric type (nested types, arrays and enums are not supported yet)",
        "Hydris",
        DiagnosticSeverity.Error,
        true);

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var types = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Hydris.Contracts.ContractAttribute",
            static (node, _) => node is TypeDeclarationSyntax,
            static (syntax, _) => (INamedTypeSymbol)syntax.TargetSymbol);

        var usages = context.SyntaxProvider.ForAttributeWithMetadataName(
            "Hydris.Routing.ActionAttribute",
            static (node, _) => node is MethodDeclarationSyntax,
            static (syntax, _) => Usage(syntax));

        var combined = types.Collect().Combine(usages.Collect());
        context.RegisterSourceOutput(combined, static (production, data) => {
            var requests = new HashSet<string>();
            var responses = new HashSet<string>();
            foreach (var usage in data.Right) {
                if (usage.Request is not null)
                    requests.Add(usage.Request);
                if (usage.Response is not null)
                    responses.Add(usage.Response);
            }

            foreach (var type in data.Left) {
                var full = type.ToDisplayString(FullyQualified);
                Emit(production, type, requests.Contains(full), responses.Contains(full));
            }
        });
    }

    private static (string? Request, string? Response) Usage(GeneratorAttributeSyntaxContext syntax) {
        if (syntax.TargetSymbol is not IMethodSymbol method)
            return (null, null);

        string? request = null;
        foreach (var parameter in method.Parameters) {
            if (IsContract(parameter.Type)) {
                request = parameter.Type.ToDisplayString(FullyQualified);
                break;
            }
        }

        return (request, ResponseType(syntax));
    }

    private static bool IsContract(ITypeSymbol type) {
        foreach (var attribute in type.GetAttributes()) {
            if (attribute.AttributeClass?.Name == "ContractAttribute")
                return true;
        }

        return false;
    }

    private static string? ResponseType(GeneratorAttributeSyntaxContext syntax) {
        if (syntax.TargetNode is not MethodDeclarationSyntax method)
            return null;

        foreach (var node in method.DescendantNodes()) {
            if (node is InvocationExpressionSyntax invocation
                && invocation.Expression is MemberAccessExpressionSyntax access
                && access.Name is GenericNameSyntax generic
                && generic.Identifier.Text == "Action"
                && generic.TypeArgumentList.Arguments.Count == 1) {
                var symbol = syntax.SemanticModel.GetTypeInfo(generic.TypeArgumentList.Arguments[0]).Type;
                if (symbol is not null)
                    return symbol.ToDisplayString(FullyQualified);
            }
        }

        return null;
    }

    private static void Emit(SourceProductionContext production, INamedTypeSymbol type, bool isRequest, bool isResponse) {
        var ns = type.ContainingNamespace.IsGlobalNamespace ? null : type.ContainingNamespace.ToDisplayString();
        var keyword = type.IsRecord ? "record" : "class";
        var members = Members(type);
        var needsWrite = isResponse || !isRequest;
        var needsRead = isRequest || !isResponse;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (ns is not null) {
            sb.Append("namespace ").AppendLine(ns);
            sb.AppendLine("{");
        }
        sb.Append("    partial ").Append(keyword).Append(' ').Append(type.Name);
        sb.AppendLine(needsWrite ? " : global::Hydris.Http.IViewData" : string.Empty);
        sb.AppendLine("    {");
        var emitted = false;
        if (needsWrite) {
            EmitWrite(production, sb, type, members);
            emitted = true;
        }
        if (needsRead) {
            if (emitted)
                sb.AppendLine();
            EmitReadFrom(sb, type, members);
            sb.AppendLine();
            EmitValidate(sb, type, members);
            sb.AppendLine();
            EmitParse(sb, type);
        }
        sb.AppendLine("    }");
        if (ns is not null)
            sb.AppendLine("}");

        var hint = type.ToDisplayString(FullyQualified).Replace("global::", string.Empty).Replace('.', '_');
        production.AddSource($"{hint}.Contract.g.cs", sb.ToString());
    }

    private static void EmitWrite(
        SourceProductionContext production, StringBuilder sb, INamedTypeSymbol type, IReadOnlyList<Member> members) {
        sb.AppendLine("        void global::Hydris.Http.IViewData.Write(global::System.Text.Json.Utf8JsonWriter writer)");
        sb.AppendLine("        {");
        sb.AppendLine("            writer.WriteStartObject();");
        foreach (var member in members) {
            JsonWrite.EmitMember(production, Unsupported, sb, "            ", $"\"{member.Wire}\"", member.Type, $"this.{member.Name}", member.Location, member.Name, 0);
        }
        sb.AppendLine("            writer.WriteEndObject();");
        sb.AppendLine("        }");
    }

    private static void EmitParse(StringBuilder sb, INamedTypeSymbol type) {
        var typeName = type.Name;
        sb.Append("        public static ").Append(typeName).AppendLine("? Parse(global::System.ReadOnlySpan<byte> utf8, global::Hydris.Contracts.ContractValidation errors)");
        sb.AppendLine("        {");
        sb.AppendLine("            try");
        sb.AppendLine("            {");
        sb.AppendLine("                var reader = new global::System.Text.Json.Utf8JsonReader(utf8);");
        sb.AppendLine("                if (!reader.Read() || reader.TokenType != global::System.Text.Json.JsonTokenType.StartObject)");
        sb.AppendLine("                {");
        sb.AppendLine("                    errors.Add(\"\", \"invalid\", \"Expected a JSON object.\");");
        sb.AppendLine("                    return null;");
        sb.AppendLine("                }");
        sb.AppendLine("                return ReadFrom(ref reader, errors);");
        sb.AppendLine("            }");
        sb.AppendLine("            catch (global::System.Text.Json.JsonException)");
        sb.AppendLine("            {");
        sb.AppendLine("                errors.Add(\"\", \"invalid\", \"The request body is not valid JSON.\");");
        sb.AppendLine("                return null;");
        sb.AppendLine("            }");
        sb.AppendLine("        }");
    }

    private static void EmitReadFrom(StringBuilder sb, INamedTypeSymbol type, IReadOnlyList<Member> members) {
        var typeName = type.Name;
        sb.Append("        internal static ").Append(typeName).AppendLine(" ReadFrom(ref global::System.Text.Json.Utf8JsonReader reader, global::Hydris.Contracts.ContractValidation errors)");
        sb.AppendLine("        {");
        foreach (var member in members)
            sb.Append("            ").Append(member.Type.ToDisplayString(FullyQualified)).Append(' ').Append(member.Local).AppendLine(" = default!;");
        foreach (var member in members)
            if (member.Required && member.Type.IsValueType)
                sb.Append("            bool ").Append(member.Seen).AppendLine(" = false;");
        sb.AppendLine("            while (reader.Read() && reader.TokenType == global::System.Text.Json.JsonTokenType.PropertyName)");
        sb.AppendLine("            {");
        sb.AppendLine("                var name = reader.GetString();");
        sb.AppendLine("                reader.Read();");
        sb.AppendLine("                switch (name)");
        sb.AppendLine("                {");
        foreach (var member in members) {
            sb.Append("                    case \"").Append(member.Wire).AppendLine("\":");
            sb.AppendLine("                    {");
            JsonRead.EmitValue(sb, "                        ", member.Type, member.Local, 0);
            if (member.Required && member.Type.IsValueType)
                sb.Append("                        ").Append(member.Seen).AppendLine(" = true;");
            sb.AppendLine("                        break;");
            sb.AppendLine("                    }");
        }
        sb.AppendLine("                    default: reader.Skip(); break;");
        sb.AppendLine("                }");
        sb.AppendLine("            }");
        foreach (var member in members) {
            if (!member.Required)
                continue;
            var condition = member.Type.IsValueType ? "!" + member.Seen : member.Local + " is null";
            sb.Append("            if (").Append(condition).Append(") errors.Add(").Append(Literal(member.Wire)).Append(", \"required\", ").Append(Literal("The " + member.Wire + " field is required.")).AppendLine(");");
        }
        var arguments = string.Join(", ", members.Select(m => m.Local));
        sb.Append("            var value = new ").Append(typeName).Append('(').Append(arguments).AppendLine(");");
        sb.AppendLine("            Validate(value, errors);");
        sb.AppendLine("            return value;");
        sb.AppendLine("        }");
    }

    private static void EmitValidate(StringBuilder sb, INamedTypeSymbol type, IReadOnlyList<Member> members) {
        sb.Append("        private static void Validate(").Append(type.Name).AppendLine(" value, global::Hydris.Contracts.ContractValidation errors)");
        sb.AppendLine("        {");
        foreach (var member in members) {
            foreach (var rule in member.Rules) {
                sb.Append("            { var message = global::Hydris.Validation.Rules.Check(").Append(Literal(rule.Name)).Append(", new global::Hydris.Validation.Value { Field = ").Append(Literal(member.Wire)).Append(", Raw = value.").Append(member.Name);
                if (rule.Args.Count > 0) {
                    sb.Append(", Args = [");
                    for (var i = 0; i < rule.Args.Count; i++) {
                        if (i > 0)
                            sb.Append(", ");
                        sb.Append(Literal(rule.Args[i]));
                    }

                    sb.Append(']');
                }

                sb.Append(" }); if (message is not null) errors.Add(").Append(Literal(member.Wire)).Append(", ").Append(Literal(rule.Name)).AppendLine(", message); }");
            }
        }
        sb.AppendLine("        }");
    }

    private static string Literal(string value) =>
        Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(value, true);

    private static IReadOnlyList<Member> Members(INamedTypeSymbol type) {
        var parameterAttributes = new Dictionary<string, ImmutableArray<AttributeData>>();
        foreach (var constructor in type.InstanceConstructors) {
            if (constructor.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(constructor.Parameters[0].Type, type))
                continue;
            foreach (var parameter in constructor.Parameters)
                parameterAttributes[parameter.Name] = parameter.GetAttributes();
        }

        var primary = type.InstanceConstructors
            .Where(c => !(c.Parameters.Length == 1 && SymbolEqualityComparer.Default.Equals(c.Parameters[0].Type, type)))
            .OrderByDescending(c => c.Parameters.Length)
            .FirstOrDefault();
        if (primary is null)
            return new List<Member>();

        var members = new List<Member>();
        foreach (var parameter in primary.Parameters) {
            var attributes = parameterAttributes.TryGetValue(parameter.Name, out var found) ? found : ImmutableArray<AttributeData>.Empty;
            members.Add(new Member(parameter.Name, parameter.Type, Camel(parameter.Name), Rules(attributes), parameter.Locations.FirstOrDefault(), IsRequired(parameter.Type)));
        }

        return members;
    }

    private static IReadOnlyList<Rule> Rules(ImmutableArray<AttributeData> attributes) {
        var rules = new List<Rule>();
        foreach (var attribute in attributes) {
            var attributeClass = attribute.AttributeClass;
            if (attributeClass is null || !IsValidationAttribute(attributeClass))
                continue;

            var args = new List<string>();
            if (attributeClass.IsGenericType && attributeClass.ConstructedFrom?.ToDisplayString() == "Hydris.Validation.RuleAttribute<T>") {
                if (attributeClass.TypeArguments.Length == 0 || attributeClass.TypeArguments[0] is not INamedTypeSymbol ruleType)
                    continue;
                foreach (var argument in attribute.ConstructorArguments)
                    AppendArgs(args, argument);
                rules.Add(new Rule(RuleName(ruleType), args));
            } else if (attributeClass.ToDisplayString() == "Hydris.Validation.RuleAttribute") {
                if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Value is not string ruleName)
                    continue;
                for (var i = 1; i < attribute.ConstructorArguments.Length; i++)
                    AppendArgs(args, attribute.ConstructorArguments[i]);
                rules.Add(new Rule(ruleName, args));
            } else {
                foreach (var argument in attribute.ConstructorArguments)
                    AppendArgs(args, argument);
                rules.Add(new Rule(Snake(Strip(attributeClass.Name)), args));
            }
        }

        return rules;
    }

    private static string RuleName(INamedTypeSymbol ruleType) {
        foreach (var attribute in ruleType.GetAttributes()) {
            if (attribute.AttributeClass?.ToDisplayString() == "Hydris.Validation.ValidationRuleAttribute"
                && attribute.ConstructorArguments.Length > 0
                && attribute.ConstructorArguments[0].Value is string explicitName) {
                return explicitName;
            }
        }

        return Snake(ruleType.Name);
    }

    private static bool IsValidationAttribute(INamedTypeSymbol attributeClass) {
        for (var baseType = attributeClass.BaseType; baseType is not null; baseType = baseType.BaseType) {
            if (baseType.ToDisplayString() == "Hydris.Validation.ValidationAttribute")
                return true;
        }

        return false;
    }

    private static void AppendArgs(List<string> args, TypedConstant argument) {
        if (argument.Kind == TypedConstantKind.Array) {
            foreach (var element in argument.Values)
                args.Add(ArgText(element));
        } else {
            args.Add(ArgText(argument));
        }
    }

    private static string ArgText(TypedConstant argument) => argument.Value switch {
        null => string.Empty,
        double d => d.ToString(CultureInfo.InvariantCulture),
        float f => f.ToString(CultureInfo.InvariantCulture),
        var value => value.ToString() ?? string.Empty,
    };

    private static string Strip(string name) =>
        name.EndsWith("Attribute", StringComparison.Ordinal) ? name.Substring(0, name.Length - "Attribute".Length) : name;

    private static string Snake(string name) {
        var builder = new StringBuilder();
        for (var i = 0; i < name.Length; i++) {
            var c = name[i];
            if (char.IsUpper(c)) {
                if (i > 0)
                    builder.Append('_');
                builder.Append(char.ToLowerInvariant(c));
            } else {
                builder.Append(c);
            }
        }

        return builder.ToString();
    }

    private static string Camel(string name) =>
        name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);


    private static ITypeSymbol? UnwrapNullable(ITypeSymbol type) =>
        type is INamedTypeSymbol { OriginalDefinition.SpecialType: SpecialType.System_Nullable_T } named
            ? named.TypeArguments[0]
            : null;

    private static bool IsRequired(ITypeSymbol type) =>
        UnwrapNullable(type) is null && type.NullableAnnotation != NullableAnnotation.Annotated;

    private sealed class Member {
        public Member(string name, ITypeSymbol type, string wire, IReadOnlyList<Rule> rules, Location? location, bool required) {
            Name = name;
            Type = type;
            Wire = wire;
            Rules = rules;
            Location = location;
            Label = wire;
            Local = "arg" + name;
            Required = required;
        }

        public string Name { get; }
        public ITypeSymbol Type { get; }
        public string Wire { get; }
        public string Label { get; }
        public string Local { get; }
        public string Seen => "seen" + Name;
        public bool Required { get; }
        public IReadOnlyList<Rule> Rules { get; }
        public Location? Location { get; }
    }

    private sealed class Rule {
        public Rule(string name, IReadOnlyList<string> args) {
            Name = name;
            Args = args;
        }

        public string Name { get; }
        public IReadOnlyList<string> Args { get; }
    }
}
