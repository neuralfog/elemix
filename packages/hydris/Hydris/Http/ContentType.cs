namespace Hydris.Http;

public enum ContentType {
    Html,
    Text,
    Css,
    JavaScript,
    Json,
    ApplicationJson,
    Csv,
    Xml,
    Svg,
    Png,
    Jpeg,
    Gif,
    Webp,
    Avif,
    Icon,
    Pdf,
    Zip,
    Gzip,
    Wasm,
    Mp3,
    Wav,
    Ogg,
    Mp4,
    Webm,
    Woff,
    Woff2,
    Ttf,
    Otf,
    OctetStream,
}

public static class ContentTypes {
    public static string Mime(this ContentType type) => type switch {
        ContentType.Html => "text/html; charset=utf-8",
        ContentType.Text => "text/plain; charset=utf-8",
        ContentType.Css => "text/css; charset=utf-8",
        ContentType.JavaScript => "text/javascript; charset=utf-8",
        ContentType.Json => "application/json; charset=utf-8",
        ContentType.ApplicationJson => "application/json",
        ContentType.Csv => "text/csv; charset=utf-8",
        ContentType.Xml => "application/xml",
        ContentType.Svg => "image/svg+xml",
        ContentType.Png => "image/png",
        ContentType.Jpeg => "image/jpeg",
        ContentType.Gif => "image/gif",
        ContentType.Webp => "image/webp",
        ContentType.Avif => "image/avif",
        ContentType.Icon => "image/x-icon",
        ContentType.Pdf => "application/pdf",
        ContentType.Zip => "application/zip",
        ContentType.Gzip => "application/gzip",
        ContentType.Wasm => "application/wasm",
        ContentType.Mp3 => "audio/mpeg",
        ContentType.Wav => "audio/wav",
        ContentType.Ogg => "audio/ogg",
        ContentType.Mp4 => "video/mp4",
        ContentType.Webm => "video/webm",
        ContentType.Woff => "font/woff",
        ContentType.Woff2 => "font/woff2",
        ContentType.Ttf => "font/ttf",
        ContentType.Otf => "font/otf",
        ContentType.OctetStream => "application/octet-stream",
        _ => "application/octet-stream",
    };
}
