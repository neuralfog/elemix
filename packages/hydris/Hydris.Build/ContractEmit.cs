using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hydris.Build;

public static class ContractEmit {
    private static readonly string[] SkipSegments = ["obj", "bin", "node_modules", ".git"];

    public static int Run(string root, string viewsRoot) {
        var contracts = new Dictionary<string, ContractDef>();
        var enums = new Dictionary<string, EnumDef>();
        var actions = new List<ActionDef>();

        foreach (var file in Sources(root)) {
            var node = CSharpSyntaxTree.ParseText(File.ReadAllText(file)).GetRoot();
            foreach (var record in node.DescendantNodes().OfType<RecordDeclarationSyntax>()) {
                if (record.ParameterList is null || !HasAttribute(record.AttributeLists, "Contract"))
                    continue;
                var def = ReadContract(record);
                contracts[def.Name] = def;
            }
            foreach (var declaration in node.DescendantNodes().OfType<EnumDeclarationSyntax>()) {
                var members = declaration.Members.Select(m => m.Identifier.Text).ToArray();
                enums[declaration.Identifier.Text] = new EnumDef(declaration.Identifier.Text, members);
            }
            foreach (var method in node.DescendantNodes().OfType<MethodDeclarationSyntax>()) {
                if (!HasAttribute(method.AttributeLists, "Action"))
                    continue;
                var action = ReadAction(method);
                if (action is not null)
                    actions.Add(action);
            }
        }

        if (contracts.Count == 0 && actions.Count == 0)
            return 0;

        var dir = Path.Combine(viewsRoot, "Views", "actions");
        Directory.CreateDirectory(dir);

        File.WriteAllText(Path.Combine(dir, "index.ts"), EmitIndex());
        foreach (var action in actions)
            File.WriteAllText(Path.Combine(dir, action.Name + ".ts"), EmitActionFile(action, contracts, enums));

        Brand.Info($"generated {actions.Count} action(s) and {contracts.Count} contract(s) to Views/actions");
        return actions.Count;
    }

    private static string EmitIndex() {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine();
        sb.AppendLine("export type FieldError = { field: string; code: string; message: string };");
        sb.AppendLine();
        sb.AppendLine("export enum Method {");
        sb.AppendLine("    Get = 'GET',");
        sb.AppendLine("    Post = 'POST',");
        sb.AppendLine("    Put = 'PUT',");
        sb.AppendLine("    Patch = 'PATCH',");
        sb.AppendLine("    Delete = 'DELETE',");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export enum ActionErrorKind {");
        sb.AppendLine("    Validation = 'validation',");
        sb.AppendLine("    Http = 'http',");
        sb.AppendLine("    Network = 'network',");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("export type ActionError =");
        sb.AppendLine("    | { kind: ActionErrorKind.Validation; errors: FieldError[] }");
        sb.AppendLine("    | { kind: ActionErrorKind.Http; status: number }");
        sb.AppendLine("    | { kind: ActionErrorKind.Network };");
        sb.AppendLine();
        sb.AppendLine("export type ActionState<T> = {");
        sb.AppendLine("    data: T | null;");
        sb.AppendLine("    loading: boolean;");
        sb.AppendLine("    isError: boolean;");
        sb.AppendLine("    error: ActionError | null;");
        sb.AppendLine("};");
        return sb.ToString();
    }

    private static string EmitActionFile(
        ActionDef action,
        Dictionary<string, ContractDef> contracts,
        Dictionary<string, EnumDef> enums) {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("import { reactive } from '@neuralfog/elemix';");
        sb.AppendLine("import type { ActionState, FieldError } from './index';");
        sb.AppendLine("import { ActionErrorKind, Method } from './index';");
        sb.AppendLine();

        var order = new List<string>();
        var seen = new HashSet<string>();
        Collect(action.Request, contracts, enums, order, seen);
        Collect(action.Response, contracts, enums, order, seen);

        foreach (var name in order) {
            if (enums.TryGetValue(name, out var declaration)) {
                EmitEnum(sb, declaration);
                sb.AppendLine();
            } else if (contracts.TryGetValue(name, out var contract)) {
                EmitContractType(sb, contract, contracts, enums);
                sb.AppendLine();
            }
        }

        var requestType = action.Request is null ? null : MapType(action.Request, contracts, enums);
        var responseType = MapType(action.Response, contracts, enums);
        EmitAction(sb, action, requestType, responseType);
        return sb.ToString();
    }

    private static void Collect(
        string? raw,
        Dictionary<string, ContractDef> contracts,
        Dictionary<string, EnumDef> enums,
        List<string> order,
        HashSet<string> seen) {
        if (raw is null)
            return;
        var core = Core(raw);
        if (!seen.Add(core))
            return;
        if (contracts.TryGetValue(core, out var contract)) {
            foreach (var field in contract.Fields)
                Collect(field.Raw, contracts, enums, order, seen);
            order.Add(core);
        } else if (enums.ContainsKey(core)) {
            order.Add(core);
        }
    }

    private static void EmitContractType(
        StringBuilder sb,
        ContractDef contract,
        Dictionary<string, ContractDef> contracts,
        Dictionary<string, EnumDef> enums) {
        sb.Append("export type ").Append(contract.Name).AppendLine(" = {");
        foreach (var field in contract.Fields)
            sb.Append("    ").Append(field.Name).Append(": ").Append(MapType(field.Raw, contracts, enums)).AppendLine(";");
        sb.AppendLine("};");
    }

    private static void EmitAction(StringBuilder sb, ActionDef action, string? requestType, string responseType) {
        var handle = Pascal(action.Name) + "Action";
        var runParam = requestType is null ? string.Empty : $"body: {requestType}";

        sb.Append("export type ").Append(handle).Append(" = ActionState<").Append(responseType).AppendLine("> & {");
        sb.Append("    run(").Append(runParam).AppendLine("): Promise<void>;");
        sb.AppendLine("};");
        sb.AppendLine();
        sb.Append("export const ").Append(SafeIdent(action.Name)).Append(" = (): ").Append(handle).AppendLine(" =>");
        sb.Append("    reactive<").Append(handle).AppendLine(">({");
        sb.AppendLine("        data: null,");
        sb.AppendLine("        loading: false,");
        sb.AppendLine("        isError: false,");
        sb.AppendLine("        error: null,");
        sb.Append("        async run(").Append(runParam).AppendLine("): Promise<void> {");
        sb.AppendLine("            this.data = null;");
        sb.AppendLine("            this.error = null;");
        sb.AppendLine("            this.isError = false;");
        sb.AppendLine("            this.loading = true;");
        sb.AppendLine("            try {");
        sb.Append("                const response = await fetch('").Append(action.Path).AppendLine("', {");
        sb.Append("                    method: Method.").Append(action.Verb).AppendLine(",");
        if (requestType is not null) {
            sb.AppendLine("                    headers: { 'Content-Type': 'application/json' },");
            sb.AppendLine("                    body: JSON.stringify(body),");
        }
        sb.AppendLine("                });");
        sb.AppendLine("                if (response.ok) {");
        sb.Append("                    this.data = (await response.json()) as ").Append(responseType).AppendLine(";");
        sb.AppendLine("                } else if (response.status === 400) {");
        sb.AppendLine("                    const problem = (await response.json()) as {");
        sb.AppendLine("                        errors: FieldError[];");
        sb.AppendLine("                    };");
        sb.AppendLine("                    this.error = {");
        sb.AppendLine("                        kind: ActionErrorKind.Validation,");
        sb.AppendLine("                        errors: problem.errors,");
        sb.AppendLine("                    };");
        sb.AppendLine("                    this.isError = true;");
        sb.AppendLine("                } else {");
        sb.AppendLine("                    this.error = {");
        sb.AppendLine("                        kind: ActionErrorKind.Http,");
        sb.AppendLine("                        status: response.status,");
        sb.AppendLine("                    };");
        sb.AppendLine("                    this.isError = true;");
        sb.AppendLine("                }");
        sb.AppendLine("            } catch {");
        sb.AppendLine("                this.error = { kind: ActionErrorKind.Network };");
        sb.AppendLine("                this.isError = true;");
        sb.AppendLine("            } finally {");
        sb.AppendLine("                this.loading = false;");
        sb.AppendLine("            }");
        sb.AppendLine("        },");
        sb.AppendLine("    });");
    }

    private static string MapType(
        string raw,
        Dictionary<string, ContractDef> contracts,
        Dictionary<string, EnumDef> enums) {
        raw = raw.Trim();
        if (raw.EndsWith("?", StringComparison.Ordinal))
            return MapType(raw.Substring(0, raw.Length - 1), contracts, enums) + " | null";
        if (raw.EndsWith("[]", StringComparison.Ordinal))
            return Wrap(MapType(raw.Substring(0, raw.Length - 2), contracts, enums)) + "[]";
        var open = raw.IndexOf('<');
        if (open > 0 && raw.EndsWith(">", StringComparison.Ordinal)) {
            var outer = raw.Substring(0, open);
            var inner = raw.Substring(open + 1, raw.Length - open - 2);
            if (outer is "List" or "IList" or "IReadOnlyList" or "ICollection"
                or "IReadOnlyCollection" or "IEnumerable" or "HashSet")
                return Wrap(MapType(inner, contracts, enums)) + "[]";
        }
        if (enums.ContainsKey(raw))
            return raw;
        if (contracts.ContainsKey(raw))
            return raw;
        return raw switch {
            "string" => "string",
            "bool" => "boolean",
            "int" or "long" or "short" or "byte" or "sbyte"
                or "uint" or "ushort" or "ulong" or "float" or "double" or "decimal" => "number",
            "DateTime" or "DateTimeOffset" or "DateOnly" or "TimeOnly" or "Guid" => "string",
            _ => "unknown",
        };
    }

    private static string Wrap(string ts) => ts.Contains(' ') ? $"({ts})" : ts;

    private static void EmitEnum(StringBuilder sb, EnumDef declaration) {
        sb.Append("export enum ").Append(declaration.Name).AppendLine(" {");
        foreach (var member in declaration.Members)
            sb.Append("    ").Append(member).Append(" = '").Append(member).AppendLine("',");
        sb.AppendLine("}");
    }

    private static string Core(string raw) {
        raw = raw.Trim();
        if (raw.EndsWith("?", StringComparison.Ordinal))
            return Core(raw.Substring(0, raw.Length - 1));
        if (raw.EndsWith("[]", StringComparison.Ordinal))
            return Core(raw.Substring(0, raw.Length - 2));
        var open = raw.IndexOf('<');
        if (open > 0 && raw.EndsWith(">", StringComparison.Ordinal))
            return Core(raw.Substring(open + 1, raw.Length - open - 2));
        return raw;
    }

    private static readonly HashSet<string> Reserved = new(StringComparer.Ordinal) {
        "break", "case", "catch", "class", "const", "continue", "debugger", "default",
        "delete", "do", "else", "enum", "export", "extends", "false", "finally", "for",
        "function", "if", "import", "in", "instanceof", "new", "null", "return", "super",
        "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with",
        "yield", "let", "static", "await", "implements", "interface", "package", "private",
        "protected", "public",
    };

    private static string SafeIdent(string name) =>
        Reserved.Contains(name) ? name + "Action" : name;

    private static string Pascal(string name) =>
        name.Length == 0 ? name : char.ToUpperInvariant(name[0]) + name.Substring(1);

    private static ContractDef ReadContract(RecordDeclarationSyntax record) {
        var fields = new List<FieldDef>();
        foreach (var parameter in record.ParameterList!.Parameters) {
            if (parameter.Type is null)
                continue;
            fields.Add(new FieldDef(Camel(parameter.Identifier.Text), parameter.Type.ToString()));
        }

        return new ContractDef(record.Identifier.Text, fields);
    }

    private static ActionDef? ReadAction(MethodDeclarationSyntax method) {
        string? verb = null;
        string? path = null;
        foreach (var list in method.AttributeLists) {
            foreach (var attribute in list.Attributes) {
                var name = AttrName(attribute.Name);
                if (name is not ("Get" or "Post" or "Put" or "Patch" or "Delete"))
                    continue;
                if (attribute.ArgumentList?.Arguments.FirstOrDefault()?.Expression is LiteralExpressionSyntax literal) {
                    verb = name;
                    path = literal.Token.ValueText;
                }
            }
        }

        if (verb is null || path is null)
            return null;

        var request = method.ParameterList.Parameters.Count == 1
            ? method.ParameterList.Parameters[0].Type?.ToString()
            : null;

        return new ActionDef(verb, path, Camel(method.Identifier.Text), request, Response(method.ReturnType));
    }

    private static string Response(TypeSyntax returnType) {
        if (returnType is GenericNameSyntax generic
            && generic.Identifier.Text is "Task" or "ValueTask"
            && generic.TypeArgumentList.Arguments.Count == 1)
            return generic.TypeArgumentList.Arguments[0].ToString();

        return returnType.ToString();
    }

    private static bool HasAttribute(SyntaxList<AttributeListSyntax> lists, string name) {
        foreach (var list in lists) {
            foreach (var attribute in list.Attributes) {
                if (AttrName(attribute.Name) == name)
                    return true;
            }
        }

        return false;
    }

    private static string AttrName(NameSyntax name) {
        var text = name switch {
            QualifiedNameSyntax qualified => qualified.Right.Identifier.Text,
            SimpleNameSyntax simple => simple.Identifier.Text,
            _ => name.ToString(),
        };
        return text.EndsWith("Attribute", StringComparison.Ordinal) ? text.Substring(0, text.Length - 9) : text;
    }

    private static string Camel(string name) =>
        name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

    private static IEnumerable<string> Sources(string root) {
        foreach (var file in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories)) {
            if (!Skipped(file))
                yield return file;
        }
    }

    private static bool Skipped(string path) {
        foreach (var segment in SkipSegments) {
            if (path.Contains($"{Path.DirectorySeparatorChar}{segment}{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
                return true;
        }

        return false;
    }

    private sealed record FieldDef(string Name, string Raw);

    private sealed record EnumDef(string Name, IReadOnlyList<string> Members);

    private sealed record ContractDef(string Name, IReadOnlyList<FieldDef> Fields);

    private sealed record ActionDef(string Verb, string Path, string Name, string? Request, string Response);
}
