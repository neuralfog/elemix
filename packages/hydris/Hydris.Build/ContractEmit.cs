using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Hydris.Build;

public static class ContractEmit {
    private static readonly string[] SkipSegments = ["obj", "bin", "node_modules", ".git"];

    public static int Run(string root, string viewsRoot) {
        var contracts = new List<ContractDef>();
        var actions = new List<ActionDef>();

        foreach (var file in Sources(root)) {
            var node = CSharpSyntaxTree.ParseText(File.ReadAllText(file)).GetRoot();
            foreach (var record in node.DescendantNodes().OfType<RecordDeclarationSyntax>()) {
                if (record.ParameterList is null || !HasAttribute(record.AttributeLists, "Contract"))
                    continue;
                contracts.Add(ReadContract(record));
            }
            foreach (var method in node.DescendantNodes().OfType<MethodDeclarationSyntax>()) {
                if (!HasAttribute(method.AttributeLists, "Action"))
                    continue;
                var action = ReadAction(method);
                if (action is not null)
                    actions.Add(action);
            }
        }

        if (contracts.Count == 0 && actions.Count == 0)
            return 0;

        var dir = Path.Combine(viewsRoot, "Views", "actions");
        Directory.CreateDirectory(dir);

        var byName = new Dictionary<string, ContractDef>();
        foreach (var contract in contracts)
            byName[contract.Name] = contract;

        File.WriteAllText(Path.Combine(dir, "index.ts"), EmitIndex());
        foreach (var action in actions)
            File.WriteAllText(Path.Combine(dir, action.Name + ".ts"), EmitActionFile(action, byName));

        Brand.Info($"generated {actions.Count} action(s) and {contracts.Count} contract(s) to Views/actions");
        return actions.Count;
    }

    private static string EmitIndex() {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine();
        sb.AppendLine("export type FieldError = { field: string; code: string; message: string };");
        sb.AppendLine();
        sb.AppendLine("export type ActionError =");
        sb.AppendLine("    | { kind: 'validation'; errors: FieldError[] }");
        sb.AppendLine("    | { kind: 'http'; status: number }");
        sb.AppendLine("    | { kind: 'network' };");
        sb.AppendLine();
        sb.AppendLine("export type ActionState<T> = {");
        sb.AppendLine("    data: T | null;");
        sb.AppendLine("    loading: boolean;");
        sb.AppendLine("    isError: boolean;");
        sb.AppendLine("    error: ActionError | null;");
        sb.AppendLine("};");
        return sb.ToString();
    }

    private static string EmitActionFile(ActionDef action, Dictionary<string, ContractDef> byName) {
        var requestContract = action.Request is not null && byName.TryGetValue(action.Request, out var request) ? request : null;
        var responseContract = byName.TryGetValue(action.Response, out var response) ? response : null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("import type { ActionState, FieldError } from './index';");
        sb.AppendLine();
        if (requestContract is not null) {
            EmitContractType(sb, action.Request!, requestContract.Fields);
            sb.AppendLine();
        }
        if (responseContract is not null) {
            EmitContractType(sb, action.Response, responseContract.Fields);
            sb.AppendLine();
        }
        EmitAction(sb, action, action.Request, action.Response);
        return sb.ToString();
    }

    private static void EmitContractType(StringBuilder sb, string name, IReadOnlyList<FieldDef> fields) {
        sb.Append("export type ").Append(name).AppendLine(" = {");
        foreach (var field in fields)
            sb.Append("    ").Append(field.Name).Append(": ").Append(field.TsType).AppendLine(";");
        sb.AppendLine("};");
    }

    private static void EmitAction(StringBuilder sb, ActionDef action, string? requestType, string responseType) {
        var factory = action.Name + "State";
        var parameter = requestType is null ? string.Empty : $"body: {requestType}";

        sb.Append("export const ").Append(factory).Append(" = (): ActionState<").Append(responseType).AppendLine("> => ({");
        sb.AppendLine("    data: null,");
        sb.AppendLine("    loading: false,");
        sb.AppendLine("    isError: false,");
        sb.AppendLine("    error: null,");
        sb.AppendLine("});");
        sb.AppendLine();
        sb.AppendLine("// #state");
        sb.Append("const state: ActionState<").Append(responseType).AppendLine("> = {");
        sb.AppendLine("    data: null,");
        sb.AppendLine("    loading: false,");
        sb.AppendLine("    isError: false,");
        sb.AppendLine("    error: null,");
        sb.AppendLine("};");
        sb.AppendLine();
        sb.Append("export const ").Append(action.Name).Append(" = async (").Append(parameter).Append("): Promise<ActionState<").Append(responseType).AppendLine(">> => {");
        sb.AppendLine("    state.data = null;");
        sb.AppendLine("    state.error = null;");
        sb.AppendLine("    state.isError = false;");
        sb.AppendLine("    state.loading = true;");
        sb.AppendLine("    try {");
        sb.Append("        const response = await fetch('").Append(action.Path).AppendLine("', {");
        sb.Append("            method: '").Append(action.Verb.ToUpperInvariant()).AppendLine("',");
        if (requestType is not null) {
            sb.AppendLine("            headers: { 'Content-Type': 'application/json' },");
            sb.AppendLine("            body: JSON.stringify(body),");
        }
        sb.AppendLine("        });");
        sb.AppendLine("        if (response.ok) {");
        sb.Append("            state.data = (await response.json()) as ").Append(responseType).AppendLine(";");
        sb.AppendLine("        } else if (response.status === 400) {");
        sb.AppendLine("            const problem = (await response.json()) as { errors: FieldError[] };");
        sb.AppendLine("            state.error = { kind: 'validation', errors: problem.errors };");
        sb.AppendLine("            state.isError = true;");
        sb.AppendLine("        } else {");
        sb.AppendLine("            state.error = { kind: 'http', status: response.status };");
        sb.AppendLine("            state.isError = true;");
        sb.AppendLine("        }");
        sb.AppendLine("    } catch {");
        sb.AppendLine("        state.error = { kind: 'network' };");
        sb.AppendLine("        state.isError = true;");
        sb.AppendLine("    } finally {");
        sb.AppendLine("        state.loading = false;");
        sb.AppendLine("    }");
        sb.AppendLine("    return state;");
        sb.AppendLine("};");
    }

    private static ContractDef ReadContract(RecordDeclarationSyntax record) {
        var fields = new List<FieldDef>();
        foreach (var parameter in record.ParameterList!.Parameters) {
            if (parameter.Type is null)
                continue;
            fields.Add(new FieldDef(Camel(parameter.Identifier.Text), MapType(parameter.Type.ToString())));
        }

        return new ContractDef(record.Identifier.Text, fields);
    }

    private static ActionDef? ReadAction(MethodDeclarationSyntax method) {
        string? verb = null;
        string? path = null;
        foreach (var list in method.AttributeLists) {
            foreach (var attribute in list.Attributes) {
                var name = AttrName(attribute.Name);
                if (name is not ("Get" or "Post" or "Put" or "Patch" or "Delete"))
                    continue;
                if (attribute.ArgumentList?.Arguments.FirstOrDefault()?.Expression is LiteralExpressionSyntax literal) {
                    verb = name;
                    path = literal.Token.ValueText;
                }
            }
        }

        if (verb is null || path is null)
            return null;

        var request = method.ParameterList.Parameters.Count == 1
            ? method.ParameterList.Parameters[0].Type?.ToString()
            : null;

        return new ActionDef(verb, path, Camel(method.Identifier.Text), request, Response(method.ReturnType));
    }

    private static string Response(TypeSyntax returnType) {
        if (returnType is GenericNameSyntax generic
            && generic.Identifier.Text is "Task" or "ValueTask"
            && generic.TypeArgumentList.Arguments.Count == 1)
            return MapType(generic.TypeArgumentList.Arguments[0].ToString());

        return MapType(returnType.ToString());
    }

    private static string MapType(string csType) {
        var nullable = csType.EndsWith("?", StringComparison.Ordinal);
        var baseType = nullable ? csType.Substring(0, csType.Length - 1) : csType;
        var ts = baseType switch {
            "string" => "string",
            "bool" => "boolean",
            "int" or "long" or "short" or "byte" or "sbyte"
                or "uint" or "ushort" or "ulong" or "float" or "double" or "decimal" => "number",
            _ => baseType,
        };
        return nullable ? ts + " | null" : ts;
    }

    private static bool HasAttribute(SyntaxList<AttributeListSyntax> lists, string name) {
        foreach (var list in lists) {
            foreach (var attribute in list.Attributes) {
                if (AttrName(attribute.Name) == name)
                    return true;
            }
        }

        return false;
    }

    private static string AttrName(NameSyntax name) {
        var text = name switch {
            QualifiedNameSyntax qualified => qualified.Right.Identifier.Text,
            SimpleNameSyntax simple => simple.Identifier.Text,
            _ => name.ToString(),
        };
        return text.EndsWith("Attribute", StringComparison.Ordinal) ? text.Substring(0, text.Length - 9) : text;
    }

    private static string Camel(string name) =>
        name.Length == 0 ? name : char.ToLowerInvariant(name[0]) + name.Substring(1);

    private static IEnumerable<string> Sources(string root) {
        foreach (var file in Directory.EnumerateFiles(root, "*.cs", SearchOption.AllDirectories)) {
            if (!Skipped(file))
                yield return file;
        }
    }

    private static bool Skipped(string path) {
        foreach (var segment in SkipSegments) {
            if (path.Contains($"{Path.DirectorySeparatorChar}{segment}{Path.DirectorySeparatorChar}", StringComparison.Ordinal))
                return true;
        }

        return false;
    }

    private sealed record FieldDef(string Name, string TsType);

    private sealed record ContractDef(string Name, IReadOnlyList<FieldDef> Fields);

    private sealed record ActionDef(string Verb, string Path, string Name, string? Request, string Response);
}
